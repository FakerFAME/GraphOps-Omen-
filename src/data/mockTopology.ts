export type NodeType = 'Identity' | 'Asset' | 'Vulnerability';

export type ZoneType = 'DMZ' | 'Corp' | 'Prod';

export type EdgeRelationship =
  | 'CAN_ACCESS'
  | 'AUTHENTICATED_TO'
  | 'CONNECTED_TO'
  | 'HAS_VULN';

export interface GraphNode {
  id: string;
  label: string;
  type: NodeType;
  // Identity properties
  tier?: 1 | 2 | 3;
  mfa?: boolean;
  department?: string;
  identitySubType?: 'User' | 'ServiceAccount' | 'Contractor';
  // Asset properties
  zone?: ZoneType;
  criticality?: number; // 1-10
  pii_data?: boolean;
  pii_records?: number;
  compromised?: boolean;
  assetSubType?: 'Endpoint' | 'Server' | 'Database' | 'Cluster' | 'Directory';
  ip?: string;
  os?: string;
  // Vulnerability properties
  cve_id?: string;
  cvss?: number; // 0-10
  exploitable?: boolean;
  description?: string;
}

export interface GraphEdge {
  id: string;
  source: string;
  target: string;
  relationship: EdgeRelationship;
  // CAN_ACCESS properties
  port?: number;
  last_used_days?: number;
  is_standing_privilege?: boolean;
  // AUTHENTICATED_TO / CONNECTED_TO properties
  timestamp?: string;
  auth_type?: string;
  mitre_tactic?: string;
  bytes?: number;
  process?: string;
  // Attack metadata
  is_attack_edge?: boolean;
  attack_step_order?: number;
}

export interface RawSiemAlert {
  id: string;
  timestamp: string;
  severity: 'CRITICAL' | 'HIGH' | 'MEDIUM' | 'LOW';
  title: string;
  sourceHost: string;
  targetHost: string;
  mitreTactic: string;
  mitreId: string;
  rawLog: string;
  isBreachNarrative?: boolean;
  narrativeStep?: number;
}

export interface TopologyData {
  nodes: GraphNode[];
  edges: GraphEdge[];
  rawAlerts: RawSiemAlert[];
}

